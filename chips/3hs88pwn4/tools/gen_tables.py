#!/usr/bin/env python3
"""Generate the 3HS88PWN4 ROM tables (src/generated_tables.hpp).

The harmonic channels reuse the 3HS816 core and its ROMs. This chip adds:

- the 65,536-entry PCM/WT noise bits (MT19937 seed 0, first 65,536 draws,
  low bit), as in the reference.
- sin, cos and omega/sin of the WT/PCM channel filter's corner for every
  cutoff register value.
- master EQ biquad coefficients for every gain register value, and the
  compressor detector low-pass.

Usage: python tools/gen_tables.py            (rewrite the header)
       python tools/gen_tables.py --check    (exit 1 if it is stale)
"""

import argparse
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "3hs816" / "tools"))
from gen_tables import MT19937  # noqa: E402  (shared with 3HS816)

OUTPUT = HERE.parent / "src" / "generated_tables.hpp"

EQ_FRAC_BITS = 24
DETECTOR_FRAC_BITS = 28
TRIG_FRAC_BITS = 30
NOISE_LENGTH = 65536


def noise_words():
    """Noise bits packed 32 per word, bit i of word w = entry 32w + i."""
    mt = MT19937(0)
    words = [0] * (NOISE_LENGTH // 32)
    for i in range(NOISE_LENGTH):
        if mt() & 1:
            words[i // 32] |= 1 << (i % 32)
    return words


def cutoff_tables():
    """The reference's corner: omega = 2 * 3.14159265 * (cutoff + 1) * 8 / 48000."""
    one = 1 << TRIG_FRAC_BITS
    sines, cosines, ratios = [], [], []
    for cutoff in range(256):
        w = 2.0 * 3.14159265 * (cutoff + 1) * 8 / 48000.0
        sines.append(round(math.sin(w) * one))
        cosines.append(round(math.cos(w) * one))
        ratios.append(round(w / math.sin(w) * one))
    return sines, cosines, ratios


# --- Master EQ and compressor detector (RBJ cookbook, as CMyFilter) ---------


def low_shelf(freq, q, gain, rate):
    w = 2 * math.pi * freq / rate
    a = 10 ** (gain / 40)
    beta = math.sqrt(a) / q
    c, s = math.cos(w), math.sin(w)
    return ([a * ((a + 1) - (a - 1) * c + beta * s), 2 * a * ((a - 1) - (a + 1) * c),
             a * ((a + 1) - (a - 1) * c - beta * s)],
            [(a + 1) + (a - 1) * c + beta * s, -2 * ((a - 1) + (a + 1) * c),
             (a + 1) + (a - 1) * c - beta * s])


def high_shelf(freq, q, gain, rate):
    w = 2 * math.pi * freq / rate
    a = 10 ** (gain / 40)
    beta = math.sqrt(a) / q
    c, s = math.cos(w), math.sin(w)
    return ([a * ((a + 1) + (a - 1) * c + beta * s), -2 * a * ((a - 1) + (a + 1) * c),
             a * ((a + 1) + (a - 1) * c - beta * s)],
            [(a + 1) - (a - 1) * c + beta * s, 2 * ((a - 1) - (a + 1) * c),
             (a + 1) - (a - 1) * c - beta * s])


def peaking(freq, bandwidth, gain, rate):
    w = 2 * math.pi * freq / rate
    alpha = math.sin(w) * math.sinh(math.log(2) / 2 * bandwidth * w / math.sin(w))
    a = 10 ** (gain / 40)
    c = math.cos(w)
    return ([1 + alpha * a, -2 * c, 1 - alpha * a], [1 + alpha / a, -2 * c, 1 - alpha / a])


def low_pass(freq, q, rate):
    w = 2 * math.pi * freq / rate
    alpha = math.sin(w) / (2 * q)
    c = math.cos(w)
    return ([(1 - c) / 2, 1 - c, (1 - c) / 2], [1 + alpha, -2 * c, 1 - alpha])


def quantize(coefficients, frac_bits):
    """Normalize by a0 and return [b0, b1, b2, a1, a2] in Q(frac_bits)."""
    (b0, b1, b2), (a0, a1, a2) = coefficients
    scale = 1 << frac_bits
    values = [round(v / a0 * scale) for v in (b0, b1, b2, a1, a2)]
    for v in values:
        assert -(1 << 31) <= v < (1 << 31), "coefficient does not fit int32"
    return values


# The reference never passed a rate to the EQ filters, so they were designed
# for CMyFilter's 44.1 kHz default while running at 48 kHz. Kept for the tone.
EQ_DESIGN_RATE = 44100.0
EQ_Q = 1 / math.sqrt(2)


def eq_tables():
    bands = [
        lambda g: low_shelf(400.0, EQ_Q, g, EQ_DESIGN_RATE),
        lambda g: peaking(1000.0, EQ_Q, g, EQ_DESIGN_RATE),
        lambda g: high_shelf(4000.0, EQ_Q, g, EQ_DESIGN_RATE),
    ]
    return [[quantize(band(value / 8), EQ_FRAC_BITS) for value in range(256)] for band in bands]


# --- Output -----------------------------------------------------------------


def rows(values, per_line, fmt=str):
    return "\n".join(
        "    " + ", ".join(fmt(v) for v in values[i:i + per_line]) + ","
        for i in range(0, len(values), per_line)
    )


def render():
    sines, cosines, ratios = cutoff_tables()
    detector = quantize(low_pass(50.0, 1.0, 48000.0), DETECTOR_FRAC_BITS)
    out = [
        "// Generated by tools/gen_tables.py. Do not edit; rerun the script.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace hs88::tables {",
        "",
        f"constexpr int kTrigFracBits = {TRIG_FRAC_BITS};",
        f"constexpr int kEqFracBits = {EQ_FRAC_BITS};",
        f"constexpr int kDetectorFracBits = {DETECTOR_FRAC_BITS};",
        "",
        "// PCM/WT noise: bit (i % 32) of word i / 32 is entry i.",
        f"inline constexpr std::uint32_t kNoise[{NOISE_LENGTH // 32}] = {{",
        rows(noise_words(), 8, lambda v: f"0x{v:08X}"),
        "};",
        "",
        "// Channel filter corner omega = 2pi * (cutoff + 1) * 8 / 48000, in Q30.",
        "inline constexpr std::int32_t kCutoffSin[256] = {",
        rows(sines, 8),
        "};",
        "inline constexpr std::int32_t kCutoffCos[256] = {",
        rows(cosines, 8),
        "};",
        "// omega / sin(omega), for the band-pass and notch bandwidth.",
        "inline constexpr std::int32_t kCutoffOmegaOverSin[256] = {",
        rows(ratios, 8),
        "};",
        "",
        "// [band: low shelf 400 Hz, peaking 1 kHz, high shelf 4 kHz][gain register]",
        "// = {b0, b1, b2, a1, a2} / a0 in Q24.",
        "inline constexpr std::int32_t kEq[3][256][5] = {",
    ]
    for band in eq_tables():
        out.append("  {")
        for coeffs in band:
            out.append("    {" + ", ".join(str(v) for v in coeffs) + "},")
        out.append("  },")
    out += [
        "};",
        "",
        "// Compressor detector: 50 Hz low-pass, Q 1, 48 kHz; {b0, b1, b2, a1, a2} in Q28.",
        "inline constexpr std::int32_t kDetector[5] = {" + ", ".join(str(v) for v in detector) + "};",
        "",
        "}  // namespace hs88::tables",
        "",
    ]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run tools/gen_tables.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
