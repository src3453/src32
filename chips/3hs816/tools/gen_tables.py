#!/usr/bin/env python3
"""Generate the 3HS816 ROM tables (src/generated_tables.hpp).

The chip runtime is integer-only so it maps directly to RTL. Everything that
needs transcendental math is precomputed here:

- built-in waves 0-9, E, F: the exact signed 8-bit values of the 3HS88PWN4
  reference, including its float32 rounding and MT19937 (seed 0) noise.
- 2^(-x) for the exponential envelope segments.

Usage: python tools/gen_tables.py            (rewrite the header)
       python tools/gen_tables.py --check    (exit 1 if it is stale)
"""

import argparse
import math
import struct
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "generated_tables.hpp"

EXP2_FRAC_BITS = 16
EXP2_STEPS = 256


def f32(value):
    """Round a Python float to IEEE binary32, like a C float assignment."""
    return struct.unpack("<f", struct.pack("<f", value))[0]


class MT19937:
    """std::mt19937 (init_genrand). Python's random module seeds differently."""

    def __init__(self, seed):
        self.state = [0] * 624
        self.index = 624
        self.state[0] = seed & 0xFFFFFFFF
        for i in range(1, 624):
            prev = self.state[i - 1]
            self.state[i] = (1812433253 * (prev ^ (prev >> 30)) + i) & 0xFFFFFFFF

    def _twist(self):
        s = self.state
        for i in range(624):
            y = (s[i] & 0x80000000) | (s[(i + 1) % 624] & 0x7FFFFFFF)
            s[i] = s[(i + 397) % 624] ^ (y >> 1) ^ (0x9908B0DF if y & 1 else 0)
        self.index = 0

    def __call__(self):
        if self.index >= 624:
            self._twist()
        y = self.state[self.index]
        self.index += 1
        y ^= y >> 11
        y ^= (y << 7) & 0x9D2C5680
        y ^= (y << 15) & 0xEFC60000
        y ^= y >> 18
        return y & 0xFFFFFFFF


def sine_turns(turns):
    # Reference: float sind(float t) { return sin((float)t * 2 * M_PI); }
    return f32(math.sin(f32(turns * 2) * math.pi))


def builtin_waves():
    """Waves 0..15 of the reference; 10..13 (user waves) are left zero."""
    waves = [[0] * 256 for _ in range(16)]
    noise = MT19937(0)
    for _ in range(65536):  # the reference's PCM noise table, drawn first
        noise()
    for i in range(256):
        x = float(i)
        full = sine_turns(f32(x / 256))
        double = sine_turns(f32(x / 128))
        tri = f32(x / 64) - 1.0 if i < 128 else f32(x / -64) + 3.0
        saw = f32(x / 128) - 1.0
        waves[0][i] = int(f32(full * 127))
        waves[1][i] = int(f32(max(0.0, full) * 127))
        waves[4][(i + 64) % 256] = int(tri * 127)
        waves[5][(i + 128) % 256] = int(saw * 127)
        waves[7][(i + 64) % 256] = int(max(tri, 0.0) * 127)
        waves[8][(i + 128) % 256] = int(max(saw, 0.0) * 127)
        waves[9][i] = 127 if noise() & 1 else -128
        if i < 128:
            waves[15][i] = int(f32(abs(double) * 127))
            waves[14][i] = int(f32(abs(double) * 127))
            waves[2][i] = int(f32(double * 127))
            waves[3][i] = 127
            waves[6][i] = 127
        else:
            waves[15][i] = int(f32(-abs(double) * 127))
            waves[3][i] = -128
    return waves


def exp2_table():
    """round(2^16 * 2^(-i/256)), i = 0..256."""
    one = 1 << EXP2_FRAC_BITS
    return [round(one * 2.0 ** (-i / EXP2_STEPS)) for i in range(EXP2_STEPS + 1)]


# --- Output -----------------------------------------------------------------


def rows(values, per_line):
    return "\n".join(
        "    " + ", ".join(str(v) for v in values[i:i + per_line]) + ","
        for i in range(0, len(values), per_line)
    )


def render():
    waves = builtin_waves()

    out = [
        "// Generated by tools/gen_tables.py. Do not edit; rerun the script.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace hs816::tables {",
        "",
        f"constexpr int kExp2FracBits = {EXP2_FRAC_BITS};",
        "",
        "// Built-in waves; entries 10..13 are the user waves and stay zero here.",
        "inline constexpr std::int8_t kWaves[16][256] = {",
    ]
    for index, wave in enumerate(waves):
        out.append(f"  {{  // wave {index:X}")
        out.append(rows(wave, 16))
        out.append("  },")
    out += [
        "};",
        "",
        "// round(2^16 * 2^(-i/256)), i = 0..256.",
        "inline constexpr std::uint32_t kExp2Neg[257] = {",
        rows(exp2_table(), 8),
        "};",
        "",
        "}  // namespace hs816::tables",
        "",
    ]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run tools/gen_tables.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
