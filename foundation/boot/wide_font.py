"""Generates the console's wide font data (services/console/con_wide.c) from the Unifont ROM.

The set is the characters of JIS X 0208 plus U+FFFD. Each is shown in two cells of the
PCG mode 3 (doc/spec_VDP.md), so even a narrow Unifont glyph takes two cells.

Output: a C header with `con_wide_runs` (start << 16 | count, ascending, merged) and
`con_wide_glyphs` (32 bytes per code unit in run order, big-endian words).
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UNIFONT = ROOT / "assets/unifont-bmp.chr"
GLYPH = 32


def charset():
    """BMP code units of JIS X 0208 (EUC-JP two-byte rows 1-94) and U+FFFD."""
    units = {0xFFFD}
    for lead in range(0xA1, 0xFF):
        for trail in range(0xA1, 0xFF):
            try:
                text = bytes((lead, trail)).decode("euc_jp")
            except UnicodeDecodeError:
                continue
            if len(text) == 1:
                units.add(ord(text))
    return sorted(units)


def runs(units):
    result = []
    for unit in units:
        if result and result[-1][0] + result[-1][1] == unit:
            result[-1][1] += 1
        else:
            result.append([unit, 1])
    return result


def header_text(rom=UNIFONT):
    data = Path(rom).read_bytes()
    if len(data) != 0x10000 * GLYPH:
        raise ValueError(f"{rom}: expected {0x10000 * GLYPH} bytes")
    spans = runs(charset())
    glyphs = b"".join(data[s * GLYPH:(s + n) * GLYPH] for s, n in spans)
    words = ",".join("0x%Xu" % int.from_bytes(glyphs[i:i + 4], "big") for i in range(0, len(glyphs), 4))
    starts = ",".join("0x%Xu" % (s << 16 | n) for s, n in spans)
    return ("/* Generated by foundation/boot/wide_font.py. */\n#include <stdint.h>\n"
            f"#define CON_WIDE_RUNS {len(spans)}u\n#define CON_WIDE_WORDS {len(glyphs) // 4}u\n"
            f"static const uint32_t con_wide_runs[CON_WIDE_RUNS] = {{{starts}}};\n"
            f"static const uint32_t con_wide_glyphs[CON_WIDE_WORDS] = {{{words}}};\n")


def write_header(path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header_text(), encoding="utf-8")
    return path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path)
    write_header(parser.parse_args().output)
