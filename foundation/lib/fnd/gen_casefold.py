"""Generates casefold_table.h from a Unicode CaseFolding table.

    python foundation/lib/fnd/gen_casefold.py tools/fs2/CaseFolding-16.0.0-CF.txt

FS2 (doc/spec_FS2.md §6) compares names by the full case folding of
Unicode 16.0.0, status C and F only. The input uses the CaseFolding.txt
line format (`code; status; mapping; # name`); lines of other statuses are
ignored, so the original CaseFolding.txt works as well. The output is
written next to this script.
"""
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent


def parse(text):
    table = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = [field.strip() for field in line.split(";")[:3]]
        if status not in ("C", "F"):
            continue
        source = int(code, 16)
        if source in table:
            raise SystemExit(f"duplicate C/F mapping for U+{source:04X}")
        target = [int(cp, 16) for cp in mapping.split()]
        if not 1 <= len(target) <= 3:
            raise SystemExit(f"mapping of U+{source:04X} has {len(target)} scalars")
        table[source] = target
    return table


def render(table, source_name):
    sources = sorted(table)
    to, multi = [], []
    for cp in sources:
        target = table[cp]
        if len(target) == 1:
            to.append(target[0])
        else:
            to.append(0x80000000 | (len(multi) // 3))
            multi += target + [0] * (3 - len(target))

    def words(values):
        return ",\n".join("    " + ", ".join("0x%Xu" % v for v in values[i:i + 8])
                          for i in range(0, len(values), 8))

    return (f"/* Generated by foundation/lib/fnd/gen_casefold.py from {source_name}.\n"
            " * Unicode case folding, status C and F (doc/spec_FS2.md §6). */\n"
            "#include <stdint.h>\n\n"
            f"#define FND_CASEFOLD_COUNT {len(sources)}u\n\n"
            f"static const uint32_t fnd_cf_from[{len(sources)}] = {{\n{words(sources)}}};\n\n"
            "/* A scalar, or 0x80000000 | index of three words in fnd_cf_multi. */\n"
            f"static const uint32_t fnd_cf_to[{len(to)}] = {{\n{words(to)}}};\n\n"
            f"static const uint32_t fnd_cf_multi[{max(len(multi), 3)}] = {{\n{words(multi or [0, 0, 0])}}};\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("table", type=Path)
    parser.add_argument("-o", "--output", type=Path, default=HERE / "casefold_table.h")
    args = parser.parse_args(argv)
    table = parse(args.table.read_text(encoding="utf-8"))
    args.output.write_text(render(table, args.table.name), encoding="utf-8", newline="\n")
    print(f"Wrote {args.output} ({len(table)} mappings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
