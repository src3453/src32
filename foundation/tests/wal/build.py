"""Builds the images of the WAX v3 C toolchain test into OUT/images.h.

test.base and test.math are WALs and test.app a WAX v3, all compiled from C
with tools/llvm-src32 (--wal, --wax3, --import-wal). main.c includes images.h.

    python foundation/tests/wal/build.py OUT [--clang PATH] [-O0|-O1|-O2]
"""
import argparse
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DRIVER = ROOT / "tools/llvm-src32/driver.py"


def driver(args, source, output, *extra):
    command = [sys.executable, str(DRIVER), str(HERE / source), args.optimization, *map(str, extra),
               "-o", str(output)]
    if args.clang:
        command[2:2] = ["--clang", args.clang]
    subprocess.run(command, check=True)
    return output.read_bytes()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out", type=Path)
    parser.add_argument("--clang")
    level = parser.add_mutually_exclusive_group()
    for n in range(3):
        level.add_argument(f"-O{n}", dest="optimization", action="store_const", const=f"-O{n}")
    parser.set_defaults(optimization="-O0")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    base, math = args.out / "base.wal", args.out / "math.wal"
    images = {
        "base": driver(args, "base.c", base, "--wal", "--image-id", "test.base",
                       "--exports", HERE / "base.exports"),
        "math": driver(args, "math.c", math, "--wal", "--image-id", "test.math", "--abi-version", "1.2",
                       "--exports", HERE / "math.exports", "--import-wal", base),
    }
    # Slots 5, 6 and 4 (doc/spec_Foundation.md §5.2), each with its stack at the slot's end.
    for name, source, origin, top in (("app", "app.c", 0x00800000, 0x00C00000),
                                      ("app2", "app.c", 0x00C00000, 0x01000000),
                                      ("spin", "spin.c", 0x00600000, 0x00800000)):
        images[name] = driver(args, source, args.out / f"{name}.wax", "--wax3", "--image-id", f"test.{name}",
                              "--origin", hex(origin), "--stack-top", hex(top), "--user-stack-size", "0x1000",
                              "--import-wal", math, "--import-wal", base)
    # Big-endian words: the same bytes in SRC32 memory, 4-byte aligned.
    lines = ["/* Generated by foundation/tests/wal/build.py. */", "#include <stdint.h>", ""]
    for name, data in images.items():
        padded = data + bytes(-len(data) % 4)
        words = ",".join("0x%Xu" % int.from_bytes(padded[i:i + 4], "big") for i in range(0, len(padded), 4))
        lines.append(f"#define img_{name}_size {len(data)}u")
        lines.append(f"static const uint32_t img_{name}[{len(padded) // 4}] = {{{words}}};")
    (args.out / "images.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out / 'images.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
