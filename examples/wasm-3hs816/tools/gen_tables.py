"""Convert chips/3hs816/src/generated_tables.hpp to src/tables.rs.

The C++ header is the source of truth (written by chips/3hs816/tools/gen_tables.py).
`cargo test` fails if src/tables.rs no longer matches it.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
HEADER = HERE.parent.parent / 'chips/3hs816/src/generated_tables.hpp'
OUTPUT = HERE / 'src/tables.rs'


def numbers(text, name):
    start = text.index(name)
    body = text[text.index('{', start):text.index('};', start)]
    return [int(value) for value in re.findall(r'-?\d+', re.sub(r'//[^\n]*', '', body))]


def main():
    text = HEADER.read_text(encoding='utf-8')
    waves = numbers(text, 'kWaves[16][256]')
    exp2 = numbers(text, 'kExp2Neg[257]')
    assert len(waves) == 16 * 256 and len(exp2) == 257
    lines = [
        '// Generated by tools/gen_tables.py from chips/3hs816/src/generated_tables.hpp.',
        '// Do not edit; rerun the script.',
        '',
        '/// Built-in waves; entries 10..13 are the user waves and stay zero here.',
        'pub const WAVES: [[i8; 256]; 16] = [',
    ]
    for wave in range(16):
        lines.append('    [')
        row = waves[wave * 256:(wave + 1) * 256]
        for i in range(0, 256, 16):
            lines.append('        ' + ', '.join(str(v) for v in row[i:i + 16]) + ',')
        lines.append('    ],')
    lines += ['];', '', '/// 2^(-i/256) in Q16 for i = 0..=256.', 'pub const EXP2_NEG: [u32; 257] = [']
    for i in range(0, 257, 8):
        lines.append('    ' + ', '.join(str(v) for v in exp2[i:i + 8]) + ',')
    lines += ['];', '']
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    sys.exit(main())
